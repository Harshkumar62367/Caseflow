CREATE SCHEMA IF NOT EXISTS caseflow_demo;

CREATE TABLE IF NOT EXISTS caseflow_demo.tickets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1009) PRIMARY KEY,
  data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object')
);

CREATE TABLE IF NOT EXISTS caseflow_demo.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON caseflow_demo.sessions (expires_at);

ALTER TABLE caseflow_demo.tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE caseflow_demo.sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA caseflow_demo FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA caseflow_demo FROM PUBLIC;

